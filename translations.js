// ========== LANGUAGE SWITCHER ==========
function setLanguage(lang) {
    localStorage.setItem("ra-lang", lang);
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (translations[lang] && translations[lang][key]) {
            const textNode = [...el.childNodes].find(n => n.nodeType === Node.TEXT_NODE && n.textContent.trim() !== '');
            if (textNode) textNode.textContent = ' ' + translations[lang][key] + ' ';
            else el.textContent = translations[lang][key];
        }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
        const key = el.getAttribute("data-i18n-placeholder");
        if (translations[lang] && translations[lang][key]) {
            el.placeholder = translations[lang][key];
        }
    });
}

function getCurrentLang() {
    return localStorage.getItem("ra-lang") || "en";
}

// Apply language on page load
const savedLang = getCurrentLang();
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => setLanguage(savedLang));
} else {
    setLanguage(savedLang);
}